function daysAgo(n) {
  const d = new Date();
  d.setDate(d.getDate() - n);
  // Randomize time within the day
  d.setHours(Math.floor(Math.random() * 14) + 8); // 8 AM - 10 PM
  d.setMinutes(Math.floor(Math.random() * 60));
  d.setSeconds(Math.floor(Math.random() * 60));
  return d;
}

async function main() {
  console.log(`Seeding ${SEED_DATA.length} pitch sessions...`);

  let created = 0;
  for (const data of SEED_DATA) {
    const session = await prisma.pitchSession.create({
      data: {
        status: "COMPLETED",
        ideaText: data.ideaText,
        questions: data.questions,
        answers: data.answers,
        score: data.score,
        verdict: data.verdict,
        vcComment: data.vcComment,
        percentile: data.percentile,
        evaluationDetails: data.evaluationDetails,
        model: "seed-data",
        createdAt: data.createdAt,
      },
    });
    created++;
    const verdictEmoji = { UNICORN: "🦄", SEED: "🌱", HOLD: "🤔", COME_BACK: "👋" }[data.verdict];
    console.log(`  ${created}. ${verdictEmoji} [${data.verdict}] ${data.score}pts — ${data.ideaText.slice(0, 40)}...`);
  }

  console.log(`\nDone! Created ${created} pitch sessions.`);
  console.log(`Distribution: UNICORN=3, SEED=7, HOLD=6, COME_BACK=4`);
}

