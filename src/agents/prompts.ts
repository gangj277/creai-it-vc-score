export type SpecialistKey = keyof typeof SPECIALIST_PROMPTS;

export function specialistUserPrompt(
  ideaText: string,
  questions: { question: string }[],
  answers: string[],
): string {
  const qaSection = questions
    .map((q, i) => `Q${i + 1}. ${q.question}\nA${i + 1}. ${answers[i] || "(답변 없음)"}`)
    .join("\n\n");

  return `다음 스타트업 아이디어와 창업자의 답변을 바탕으로 담당 항목을 평가해주세요:

## 아이디어
"${ideaText}"

## 후속 Q&A
${qaSection}`;
}

