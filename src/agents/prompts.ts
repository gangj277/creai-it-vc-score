export function synthesizerUserPrompt(
  ideaText: string,
  totalScore: number,
  verdict: string,
  breakdown: { dimension: string; score: number; weight: number; confidence: string; comment: string }[],
): string {
  const breakdownText = breakdown
    .map((d) => `- ${d.dimension}: ${d.score}점/100 (가중치 ${d.weight}%, 확신도 ${d.confidence}) — "${d.comment}"`)
    .join("\n");

  return `다음 스타트업 아이디어에 대해 5명의 전문 심사역이 평가한 결과입니다.
리드 파트너로서 최종 종합 의견을 작성해주세요.

## 아이디어
"${ideaText}"

## 종합 점수: ${totalScore}점 / 100 (판정: ${verdict})

## 전문 심사역 평가 결과
${breakdownText}

위 결과를 종합하여 vcComment, percentile, highlights, improvements를 JSON으로 반환해주세요.`;
}
